/**
 * Dev-Level-1 — Planner tier (FR-004).
 * Honors `simplebugs.skipPlanning`, Access Mode Pills
 * (`plan-read-only` | `plan-gate` | `full-factory`), emits `plan.md` in the
 * configured locale (ar | en | fr | tr) with code identifiers and file paths
 * preserved strictly LTR (ADR-081), and validates every planned target file
 * against the synchronous `BlastRadiusGuard` before handoff (SC-004).
 */

export type AccessModePill = 'plan-read-only' | 'plan-gate' | 'full-factory';
export type SupportedLocale = 'en' | 'ar' | 'fr' | 'tr';

export interface RunPlannerTierOptions {
  taskId: string;
  briefMarkdown: string;
  accessMode: AccessModePill;
  locale?: SupportedLocale;
  skipPlanningForSimpleBug?: boolean;
  isSimpleBug?: boolean;
  plannedTargetFiles: string[];
  blastRadiusGuard: BlastRadiusGuard;
  litellmClient?: LiteLLMClient;
}

export interface PlannerTierResult {
  skipped: boolean;
  awaitingHumanPlanApproval: boolean;
  planMarkdown: string;
  validatedFiles: string[];
}

const LTR_ISOLATE_START = '\u2066'; // LEFT-TO-RIGHT ISOLATE
