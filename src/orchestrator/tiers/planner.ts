/** Wraps code identifiers / file paths in LTR isolates (ADR-081). */
function ltr(token: string): string {
  return `${LTR_ISOLATE_START}${token}${LTR_ISOLATE_END}`;
}

/**
 * Validates planned target files against the synchronous BlastRadiusGuard.
 * Forbidden (Rule 0 / forbiddenGlobs) paths throw immediately; read-only /
 * default-deny (`escalate`) files are rejected because planner target files
 * must be inside the writable scope before handoff (SC-004).
 */
function validateTargetFiles(
  plannedTargetFiles: string[],
  blastRadiusGuard: BlastRadiusGuard
): string[] {
  const validatedFiles: string[] = [];
  for (const targetFile of plannedTargetFiles) {
    let decision: 'allow' | 'escalate';
    try {
      decision = blastRadiusGuard.evaluate(targetFile, 'write');
    } catch (error) {
      if (error instanceof BlastRadiusViolationError) throw error;
      throw new GraywolfAppError(
        'RELAY_BLAST_RADIUS_VIOLATION',
        `BlastRadiusGuard rejected planned target file '${targetFile}'`,
        { targetFile }
      );
    }
    if (decision !== 'allow') {
      throw new BlastRadiusViolationError(
        targetFile,
        'write',
        'Planned target file is outside the writable blast radius (read-only / default-deny)'
      );
    }
    validatedFiles.push(targetFile);
  }
  return validatedFiles;
}

function renderDeterministicPlan(options: {
  taskId: string;
  briefMarkdown: string;
  accessMode: AccessModePill;
  localeStrings: LocaleStrings;
  validatedFiles: string[];
}): string {
  const { taskId, briefMarkdown, accessMode, localeStrings, validatedFiles } = options;
  return [
    localeStrings.title,
    '',
    `- Task: \`${taskId}\``,
    `- Access Mode: \`${accessMode}\``,
    '',
    localeStrings.objective,
    '',
    briefMarkdown.trim(),
    '',
    localeStrings.targetFiles,
    '',
    ...validatedFiles.map((file) => `- ${ltr(`\`${file}\``)}`),
    '',
    localeStrings.implementationNotes,
    '',
    '- Implement via `delegate-fleet.v1` (Dev-Level-3).',
    '- Respect Rule 0 forbidden scope at all times.',
    '- Route browser observations through `<untrusted_browser_observation>` only.',
    '',
    localeStrings.generatedBy,
    '',
  ].join('\n');
}

export async function runPlannerTier(options: RunPlannerTierOptions): Promise<PlannerTierResult> {
  const {
    taskId,
    briefMarkdown,
    accessMode,
    locale = 'en',
    skipPlanningForSimpleBug = false,
    isSimpleBug = false,
    plannedTargetFiles,
    blastRadiusGuard,
    litellmClient,
  } = options;

  if (!plannedTargetFiles || plannedTargetFiles.length === 0) {
    throw new GraywolfAppError('ACI_VALIDATION_FAILED', 'plannedTargetFiles must not be empty');
  }

  // Blast-radius validation runs in EVERY access mode — the planner must never
  // hand off files outside the writable scope (SC-004).
  const validatedFiles = validateTargetFiles(plannedTargetFiles, blastRadiusGuard);

  const localeStrings = LOCALES[locale];
  const shouldSkip = skipPlanningForSimpleBug && isSimpleBug;
  const awaitingHumanPlanApproval = accessMode !== 'full-factory';

  if (shouldSkip) {
    const skipMarkdown = [
      localeStrings.skipTitle,
      '',
      `- Task: ${ltr(`\`${taskId}\``)}`,
      '',
      localeStrings.skipBody,
      '',
      localeStrings.generatedBy,
      '',
    ].join('\n');
    return {
      skipped: true,
      // Even a skipped planner never writes files under plan-read-only /
      // plan-gate without the human gate.
      awaitingHumanPlanApproval: accessMode === 'full-factory' ? false : awaitingHumanPlanApproval,
      planMarkdown: skipMarkdown,
      validatedFiles,
    };
  }

  let planMarkdown = renderDeterministicPlan({
    taskId,
    briefMarkdown,
    accessMode,
    localeStrings,
    validatedFiles,
  });

  if (litellmClient) {
    const messages: ChatMessage[] = [
      {
        role: 'system',
        content:
          'You are Dev-Level-1 (agent-planner). Produce a concise, actionable implementation plan. ' +
          'Emit code identifiers and file paths in backticks (strictly LTR). Never plan writes to Rule 0 forbidden files.',
      },
      {
        role: 'user',
        content: `Task ${taskId} (access mode: ${accessMode}, locale: ${locale}).\n\nBrief:\n${briefMarkdown}\n\nPlanned target files:\n${validatedFiles.join('\n')}`,
      },
    ];
    const response = await litellmClient.complete({
      alias: 'agent-planner',
      messages,
      persona: 'planner',
      taskId,
    });
    if (response.content.trim().length > 0) {
      planMarkdown = response.content;
    }
  }

  return {
    skipped: false,
    awaitingHumanPlanApproval,
    planMarkdown,
    validatedFiles,
  };
}
