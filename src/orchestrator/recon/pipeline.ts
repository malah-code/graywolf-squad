import * as fs from 'node:fs/promises';
import * as path from 'node:path';

import { indexRepositoryAst, ExtractedFileIndex } from './ast-indexer';
import { BlastRadiusProposal, RULE_0_FORBIDDEN_GLOBS, proposeBlastRadius } from './blast-radius';
import { loadProjectConventions, LoadedConventions } from './constitution-loader';
import { fingerprintRepository, RepoFingerprint } from './fingerprint';
import { buildDependencyGraph, computePageRank } from './pagerank';

/**
 * Phase 5b — End-to-End 5-Phase Reconnaissance Orchestrator (FR-001).
 * Phases 1–4 are fully deterministic and consume 0 LLM tokens; Phase 5 merges
 * the ADR-038 convention cascade and emits the `.agents/` report artifacts
 * (`recon-report.md`, `recon-report.json` [F14 orchestrator source of truth],
 * `constitution.md`) using a deterministic Markdown template.
 */

export interface ReconPipelineOptions {
  repoRoot: string;
  featureKeywords?: string[];
  /** Writes `.agents/recon-report.md`, `.agents/recon-report.json`, `.agents/constitution.md`. Default: true. */
  writeArtifacts?: boolean;
}

export interface ReconPipelineResult {
  fingerprint: RepoFingerprint;
  fileIndices: ExtractedFileIndex[];
  pageRankScores: Record<string, number>;
  blastRadius: BlastRadiusProposal;
  conventions: LoadedConventions;
  reconReportMarkdown: string;
  reconReportJson: string;
  constitutionMarkdown: string;
}

function renderReconReportMarkdown(input: {
  fingerprint: RepoFingerprint;
  blastRadius: BlastRadiusProposal;
  topFiles: Array<{ file: string; score: number }>;
  conventions: LoadedConventions;
}): string {
  const { fingerprint, blastRadius, topFiles, conventions } = input;
  const list = (items: string[]): string =>
    items.length > 0 ? items.map((item) => `- \`${item}\``).join('\n') : '- _(none)_';

  const topFilesSection =
    topFiles.length > 0
      ? topFiles.map(({ file, score }) => `- \`${file}\` — PageRank ${score.toFixed(6)}`).join('\n')
      : '- _(no source files indexed)_';

  const watchlist = blastRadius.downstreamWatchlist;
  const watchlistSection =
    watchlist.length > 0
      ? watchlist.map((file) => `- \`${file}\``).join('\n')
      : '- _(no overflow — all direct dependents fit within the top-20 cap)_';

  return `# Brownfield Reconnaissance Report

_Generated by the deterministic 5-phase reconnaissance pipeline (0 LLM tokens)._

## 1. Detected Stack (Phase 1)

| Dimension | Values |
|---|---|
| Languages | ${fingerprint.languages.join(', ') || '_(none)_'} |
| Frameworks | ${fingerprint.frameworks.join(', ') || '_(none)_'} |
| ORMs | ${fingerprint.orms.join(', ') || '_(none)_'} |
| Test Runners | ${fingerprint.testRunners.join(', ') || '_(none)_'} |
| Package Manager | ${fingerprint.packageManager} |
| Default Test Command | \`${fingerprint.defaultTestCommand || 'unknown'}\` |
| Default Lint Command | \`${fingerprint.defaultLintCommand || 'unknown'}\` |

### CI/CD Control Files
${list(fingerprint.ciFiles)}

### Container Control Files
${list(fingerprint.containerFiles)}

### Env Templates
${list(fingerprint.envTemplates)}

## 2. PageRank Centrality (Phase 3 — Top Files)

${topFilesSection}

## 3. Proposed Blast Radius (Phase 4)

### Writable Scope (feature roots)
${list(blastRadius.writableScope)}

### Read-Only Scope (transitive upstream + bounded downstream, depth <= 1, <= 20 files)
${list(blastRadius.readOnlyScope)}

### Forbidden Scope (Rule 0 — immutable)
${list(blastRadius.forbiddenScope)}

### Downstream Regression Watchlist (beyond the top-20 PageRank cap)
${watchlistSection}

## 4. Convention Cascade (Phase 5 — ADR-038)

Sources found (in precedence order): ${
    conventions.sourcesFound.length > 0
      ? conventions.sourcesFound.map((source) => `\`${source}\``).join(' > ')
      : '_(none)_'
  }
`;
}

function renderConstitutionMarkdown(input: {
  conventions: LoadedConventions;
  forbiddenGlobs: readonly string[];
}): string {
  const { conventions, forbiddenGlobs } = input;
  return `# Project Constitution (Recon-Synthesized)

_Generated from the ADR-038 convention cascade. This file is Rule 0 protected: agents may never modify it._

## Rule 0 — Immutable Forbidden Scope

The following globs are permanently out of blast radius for every task:

${forbiddenGlobs.map((glob) => `- \`${glob}\``).join('\n')}

## Project Conventions

${conventions.mergedRulesMarkdown}
`;
}

function buildReconReportJson(input: {
  fingerprint: RepoFingerprint;
  blastRadius: BlastRadiusProposal;
  pageRankScores: Record<string, number>;
  conventions: LoadedConventions;
  generatedAt: string;
}): string {
  const { fingerprint, blastRadius, pageRankScores, conventions, generatedAt } = input;
  const topFiles = Object.entries(pageRankScores)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 20)
    .map(([file, score]) => ({ file, score: Number(score.toFixed(6)) }));

  return JSON.stringify(
    {
      schemaVersion: 'recon-report.v1',
      generatedAt,
      fingerprint,
      blastRadius,
      topFiles,
      conventionsSources: conventions.sourcesFound,
    },
    null,
    2
  );
}

export async function runReconPipeline(options: ReconPipelineOptions): Promise<ReconPipelineResult> {
  const { repoRoot, featureKeywords = [], writeArtifacts = true } = options;

  // Phases 1–4: deterministic, 0 LLM tokens
  const fingerprint = await fingerprintRepository(repoRoot);
  const fileIndices = await indexRepositoryAst(repoRoot);
  const graph = buildDependencyGraph(fileIndices);
  const pageRankScores = computePageRank(graph);
  const proposal = proposeBlastRadius({ featureKeywords, graph, pageRankScores });

  // Rule 0 system-level enforcement: CI/CD + container control files detected
  // by Phase 1 always land in forbiddenScope (FR-002).
  const controlFiles = [...fingerprint.ciFiles, ...fingerprint.containerFiles];
  const forbiddenScope = [...new Set([...proposal.forbiddenScope, ...controlFiles])].sort();
  const blastRadius: BlastRadiusProposal = { ...proposal, forbiddenScope };

  // Phase 5: convention cascade + deterministic report synthesis
  const conventions = await loadProjectConventions(repoRoot);
  const generatedAt = new Date().toISOString();
  const topFiles = Object.entries(pageRankScores)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 10)
    .map(([file, score]) => ({ file, score }));

  const reconReportMarkdown = renderReconReportMarkdown({
    fingerprint,
    blastRadius,
    topFiles,
    conventions,
  });
  const constitutionMarkdown = renderConstitutionMarkdown({
    conventions,
    forbiddenGlobs: RULE_0_FORBIDDEN_GLOBS,
  });
  const reconReportJson = buildReconReportJson({
    fingerprint,
    blastRadius,
    pageRankScores,
    conventions,
    generatedAt,
  });

  if (writeArtifacts) {
    const agentsDir = path.join(repoRoot, '.agents');
    await fs.mkdir(agentsDir, { recursive: true });
    await fs.writeFile(path.join(agentsDir, 'recon-report.md'), reconReportMarkdown, 'utf8');
    await fs.writeFile(path.join(agentsDir, 'recon-report.json'), reconReportJson, 'utf8');
    await fs.writeFile(path.join(agentsDir, 'constitution.md'), constitutionMarkdown, 'utf8');
  }

  return {
    fingerprint,
    fileIndices,
    pageRankScores,
    blastRadius,
    conventions,
    reconReportMarkdown,
    reconReportJson,
    constitutionMarkdown,
  };
}
